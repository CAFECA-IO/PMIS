/** 依領域取出知識；找不到回 null。 */
export function findDomain(id: string | null | undefined): DomainKnowledge | null {
  if (!id) return null;
  return DOMAINS.find((d) => d.id === id) ?? null;
}

/** 全部參考工程分項的總數（依名稱去重），供測試與說明使用。 */
export function totalWorkItems(): number {
  return new Set(DOMAINS.flatMap((d) => d.workItems.map((w) => w.name))).size;
}

/** 參考分項的名稱清單（供只需要名稱的呼叫端）。 */
export function workItemNames(domain: DomainKnowledge): string[] {
  return domain.workItems.map((w) => w.name);
}

/**
 * 依名稱查參考分項的單位與類別。
 *
 * 供解讀契約後回填：模型若讀出了分項名稱卻沒讀到單位，
 * 名稱恰好對得上參考清單時就用參考值，不必讓使用者逐項補。
 */
export function lookupReference(name: string): ReferenceWorkItem | null {
  const key = name.trim();
  if (!key) return null;
  for (const d of DOMAINS) {
    const hit = d.workItems.find((w) => w.name === key);
    if (hit) return hit;
  }
  return null;
}
