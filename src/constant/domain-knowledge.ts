/**
 * 詞彙來源。
 *
 * 誠實記錄很重要：verified 來自使用者提供的真實監造文件；
 * ai-pending-review 是 AI 領域知識、尚未經官方文件查證，可能有用字錯誤。
 */
export type Provenance = "verified" | "ai-pending-review";

export type DomainKnowledge = {
  id: DomainId;
  label: string;
  /** 用於辨識契約屬於此領域的關鍵詞（出現越多越可能）。 */
  keywords: string[];
  /** 主要構造物／設施單元。工程分項多以此為主語。 */
  structures: string[];
  /** 常見工序。與構造物交叉組成具體分項。 */
  sequences: string[];
  /** 主要設備／材料，多需送審與檢驗。 */
  equipment: string[];
  /** 內容來源，供審閱時判斷可信度。 */
  provenance: Provenance;
  /**
   * 參考工程分項：實務上會出現的完整分項名稱，附計量單位與 WBS 類別。
   *
   * 與 structures／sequences 的差別是「已組合完成」——
   * 可直接對照，注入時依契約內文挑相關者（見 domain-match）。
   */
  workItems: ReferenceWorkItem[];
};

/**
 * 一項參考工程分項。
 *
 * 帶單位與類別的理由 ——
 * 工程分項在估驗台帳上就是一列價目：沒有單位就無法計量，
 * 沒有 WBS 類別就無法彙整成「土建做了幾成、機電做了幾成」。
 * 只有名稱時，模型解讀契約也只能吐出一串名字，
 * 使用者仍得逐項回頭補單位。
 *
 * 單位與類別由規則推斷（依名稱關鍵詞，落空時取領域慣用預設），
 * 尚未逐項查證，請見 docs/知識庫審閱清單.md。
 */
export type ReferenceWorkItem = {
  name: string;
  /** 計量單位，如 m3、m、組、式（見 constant/ledger 的 WORK_UNITS）。 */
  unit: WorkUnit;
  /** WBS 類別 id（見 constant/ledger 的 WBS_CATEGORIES）。 */
  wbs: WbsCategoryId;
};

