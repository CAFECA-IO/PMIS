/**
 * 工程領域知識庫。
 *
 * 用途：解析契約時注入對應領域的實務用語，讓模型產出的工程分項貼近
 * 監造人員實際使用的說法，而不是「基礎開挖、鋼筋組立」這類泛用詞。
 *
 * 為何需要 ——
 * 提示詞裡若只給通用範例，模型會用通用詞回答。實際的監造文件（如
 * 「水資源回收中心新建工程」第 23 次進度及品質檢討會議施工報告）顯示，
 * 分項是以「構造物單元 × 工序」組織的：不是「沉箱工程」，而是
 * 「沉箱第一單元下沉作業」「沉箱第二單元內模組立」。設備名稱也極為具體：
 * 粗攔污柵、矩型刮泥機、帶濾式脫水機、臭氧洗滌塔。
 *
 * ⚠️ 來源與可信度
 * water 領域的詞彙取自使用者提供的真實監造報告，標為 verified。
 * 其餘領域標為 ai-pending-review —— 內容為 AI 的工程領域知識，
 * 尚未以官方文件（PCCES 工項編碼、公共工程施工綱要規範、水利署技術規範）
 * 逐項查證。用字若有誤，注入提示詞後會讓模型輸出錯的分項名稱，
 * 因此請以實際契約與估驗計價單逐域審閱後再改為 verified。
 *
 * 維護方式：程式內常數，隨版本控管、可被測試。
 */

